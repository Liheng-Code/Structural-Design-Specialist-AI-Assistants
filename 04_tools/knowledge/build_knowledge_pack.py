"""Build the NotebookLM knowledge pack: one Markdown source per discipline plus the shared core.

    python 04_tools/knowledge/build_knowledge_pack.py                  (writes 06_knowledge-pack/)
    python 04_tools/knowledge/build_knowledge_pack.py --out <dir>

File lists come from 02_disciplines/manifest.yaml. Each source file is copied in full under a heading that names its repo
path, so a NotebookLM citation leads back to the file. Upload steps: 06_knowledge-pack/README.md (written by this script).
"""
from __future__ import annotations

import argparse
import datetime as dt
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "ai"))
import project_access as pa

FENCE = {".yaml": "yaml", ".yml": "yaml", ".csv": "csv", ".json": "json", ".py": "python"}

DISCLAIMER = (
    "> Generated from the project repository. This is reference material for search and recall, not an approved "
    "standard or a calculation result. Each section names its source file; check that file's status header "
    "(APPROVED / PROPOSED / DRAFT / SKELETON). Nothing here is engineer-approved unless the source file says so. "
    "NotebookLM answers are AI summaries of this text (gap G29)."
)

README = """# NotebookLM knowledge pack

Generated by `python 04_tools/knowledge/build_knowledge_pack.py` on {date} from commit `{commit}`.

| File | Content |
|---|---|
{rows}

## Add to NotebookLM
1. Open https://notebooklm.google.com and create a notebook (for example "Structural Design Specialist").
2. **Add source -> Upload** and select every `.md` file in this folder. (Or put the folder in Google Drive and add the files as Drive sources.)
3. Optional: one notebook per discipline - upload `00_platform-core.md` plus that discipline's file.
4. After changing standards, skills or knowledge files: rebuild, delete the old sources in NotebookLM and upload the new files.

From Claude Code with the NotebookLM MCP connected, ask Claude to "register the notebook" (give it the notebook share link) so it can query the notebook.

## Rules
NotebookLM is a recall aid. Cite the repo file a NotebookLM answer points to; never cite NotebookLM itself as the source of an engineering value, clause or check result.
"""


def git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=pa.ROOT, capture_output=True, text=True,
                              check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def render(title: str, files: list[pathlib.Path], date: str, commit: str) -> str:
    out = [f"# {title}", "", f"Knowledge pack generated {date} from commit `{commit}`.", "", DISCLAIMER, "",
           "## Contents", ""]
    out += [f"- `{pa.rel(p)}`" for p in files]
    for p in files:
        body = p.read_text(encoding="utf-8", errors="replace").strip()
        out += ["", "---", "", f"## Source: `{pa.rel(p)}`", ""]
        lang = FENCE.get(p.suffix.lower())
        if lang:
            out += [f"```{lang}", body, "```"]
        else:
            # demote headings so each source stays under its "Source:" heading in NotebookLM's outline
            out += [("##" + line) if line.startswith("#") else line for line in body.splitlines()]
    return "\n".join(out) + "\n"


def build(out_dir: pathlib.Path) -> list[pathlib.Path]:
    m = pa.load_manifest()
    date = dt.date.today().isoformat()
    commit = git_commit()
    out_dir.mkdir(parents=True, exist_ok=True)
    packs = [(m["core"]["pack"], m["core"]["title"], pa.expand(m["core"]["files"]))]
    packs += [(d["pack"], d["title"], pa.expand(d["files"])) for d in m["disciplines"].values()]
    written, rows = [], []
    for name, title, files in packs:
        path = out_dir / name
        path.write_bytes(render(title, files, date, commit).encode("utf-8"))   # bytes: LF on Windows too
        written.append(path)
        rows.append(f"| `{name}` | {title} ({len(files)} source files, {path.stat().st_size // 1024} KB) |")
    (out_dir / "README.md").write_bytes(README.format(date=date, commit=commit, rows="\n".join(rows)).encode("utf-8"))
    return written


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=pathlib.Path, default=pa.paths.KNOWLEDGE_PACK)
    a = ap.parse_args()
    for p in build(a.out):
        print(f"{p}  ({p.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
